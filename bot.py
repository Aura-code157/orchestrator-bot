history = {}
def get_history(user_id):
    if user_id not in history:
        history[user_id] = deque(maxlen=8)
    return history[user_id]

def safe_md(text):
    return re.sub(r'([_*\[\]()~`>#+\-=|{}.!])', r'\\\1', text)

