@bot.message_handler(func=lambda m: True)
def general_handler(message):
    try:
        uid = message.from_user.id
        user_last_msg[uid] = time.time()

        if message.chat.type in ['group', 'supergroup']:
            if BOT_USERNAME not in message.text:
                return
            user_text = message.text.replace(f"@{BOT_USERNAME}", "").strip()
            if not user_text:
                return
        else:
            user_text = message.text.strip()
            if not user_text:
                return

        # Получаем ответ из мозга
        response = get_best_response(user_text)
        
        # Сохраняем в историю
        history = get_history(uid)
        history.append({"role": "user", "content": user_text})
        history.append({"role": "assistant", "content": response})
        
        bot.reply_to(message, response)

    except Exception as e:
        print(f"Ошибка: {e}")
        bot.reply_to(message, "⚠️ Произошла внутренняя ошибка. Но я скоро исправлюсь!")

